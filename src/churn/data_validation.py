"""Phase 0: inventory of the supplied workbook before any cleaning.

Profiles every sheet (shape, dtypes, missingness, distinct counts, ranges), checks candidate keys,
relationships and join cardinality, and writes:
    outputs/tables/table_summary.*        one row per sheet
    outputs/tables/schema_inventory.*     one row per column
    outputs/tables/integrity_checks.*     key / relationship checks with evidence
    reports/data_inventory.md             readable summary

Run:  python -m churn.data_validation
"""
from __future__ import annotations

import logging

import pandas as pd

from churn import data_loader as D
from churn.paths import P
from churn.utils import profile_frame, setup_logging, table_summary, write_table

log = logging.getLogger(__name__)


def run() -> None:
    cp, ma, cl = D.load_profile(), D.load_activity(), D.load_labels()
    summary = pd.DataFrame([
        table_summary(cp, "fb Customer Profile", ["CUSTOMER_ID"], "SIGNUP_DATE"),
        table_summary(ma, "fb Monthly Activity", ["CUSTOMER_ID", "MONTH"], "MONTH"),
        table_summary(cl, "fb Churn Label", ["CUSTOMER_ID"]),
    ])
    summary["unique_customers"] = [cp.CUSTOMER_ID.nunique(), ma.CUSTOMER_ID.nunique(), cl.CUSTOMER_ID.nunique()]
    schema = pd.concat([profile_frame(cp, "fb Customer Profile"), profile_frame(ma, "fb Monthly Activity"),
                        profile_frame(cl, "fb Churn Label")], ignore_index=True)

    ip, ia, il = set(cp.CUSTOMER_ID), set(ma.CUSTOMER_ID), set(cl.CUSTOMER_ID)
    rows_per_member = ma.drop_duplicates().groupby("CUSTOMER_ID").size()
    months = pd.date_range(ma.MONTH.min(), ma.MONTH.max(), freq="MS")
    checks = [
        ("activity customers exist in the profile table", ia <= ip, f"{len(ia - ip)} orphan IDs"),
        ("label customers == profile customers", il == ip, f"label-only {len(il - ip)}, profile-only {len(ip - il)}"),
        ("every labelled customer has activity rows", il <= ia, f"{len(il - ia)} members without any activity row"),
        ("CUSTOMER_ID unique in profile", not cp.CUSTOMER_ID.duplicated().any(),
         f"{int(cp.CUSTOMER_ID.duplicated().sum())} repeated IDs ({int(cp.duplicated().sum())} exact duplicate rows)"),
        ("CUSTOMER_ID unique in label table", not cl.CUSTOMER_ID.duplicated().any(),
         f"{int(cl.CUSTOMER_ID.duplicated().sum())} repeated IDs ({int(cl.duplicated().sum())} exact duplicate rows)"),
        ("CUSTOMER_ID + MONTH unique in activity", not ma.duplicated(["CUSTOMER_ID", "MONTH"]).any(),
         f"{int(ma.duplicated(['CUSTOMER_ID', 'MONTH']).sum())} repeated keys ({int(ma.duplicated().sum())} exact duplicate rows)"),
        ("18 consecutive activity months", ma.MONTH.nunique() == 18 and len(months) == 18,
         f"{ma.MONTH.min().date()} to {ma.MONTH.max().date()}, {ma.MONTH.nunique()} distinct months"),
        ("every member has an activity row in all 18 months", bool((rows_per_member == 18).all()),
         f"{int((rows_per_member == 18).sum())} of {len(rows_per_member)} members; rows per member median "
         f"{rows_per_member.median():.0f}, min {rows_per_member.min()} (late sign-ups, lapsed members and deleted rows)"),
        ("join grain: profile 1 : label 1 : activity many (after de-duplication)",
         cp.drop_duplicates().CUSTOMER_ID.is_unique and cl.drop_duplicates().CUSTOMER_ID.is_unique,
         "profile and label are one row per member once exact duplicates are removed; activity is one row per member-month"),
        ("label CHURNED is binary", set(cl.CHURNED.dropna().unique()) <= {0, 1},
         f"values {sorted(cl.CHURNED.dropna().unique().tolist())}, churn rate {cl.drop_duplicates().CHURNED.mean():.1%}"),
    ]
    checks = pd.DataFrame(checks, columns=["check", "passed", "evidence"])
    write_table(summary, P.tables / "table_summary", md=False)
    write_table(schema, P.tables / "schema_inventory", md=False)
    write_table(checks, P.tables / "integrity_checks", md=False)

    lines = ["# Data inventory (Phase 0)", "",
             "Generated by `python -m churn.data_validation` from the raw workbook, before any cleaning.", "",
             "## Sheets", "", summary.astype(object).where(summary.notna(), "").to_markdown(index=False), "",
             "## Keys, relationships and grain", "", checks.to_markdown(index=False), "",
             "Relationships: `fb Customer Profile` (one row per member) joins `fb Churn Label` (one row per member) "
             "and `fb Monthly Activity` (one row per member-month) on `CUSTOMER_ID`. Joining activity to the other two "
             "repeats member attributes per month, so the modelling dataset is built at member x snapshot grain instead "
             "of by a raw merge.", "",
             "## Column inventory", ""]
    for table, g in schema.groupby("table", sort=False):
        lines += [f"### {table}", "", g.drop(columns="table").fillna("").to_markdown(index=False, floatfmt=".4g"), ""]
    (P.reports / "data_inventory.md").write_text("\n".join(lines), encoding="utf-8")
    log.info("inventory written: %s", P.reports / "data_inventory.md")


if __name__ == "__main__":
    setup_logging()
    run()
